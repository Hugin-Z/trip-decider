class ResumeIntegrationCase(unittest.TestCase):
    maxDiff = None

    def acquire(
        self,
        capture_result: ResumeCaptureObservation,
        *,
        seeds: tuple[str, ...] = SEEDS,
    ):
        with tempfile.TemporaryDirectory(
            prefix="trip-decider-wu2r-resume-test-"
        ) as raw:
            root = Path(raw)
            primary = root / "runtime" / "failure-evidence.json"
            emergency = root / "emergency" / "failure-evidence.json"
            primary.parent.mkdir()
            emergency.parent.mkdir()
            capture = Mock(return_value=capture_result)
            cleanup = Mock(
                return_value=(
                    CleanupItemObservation(
                        resource_kind="synthetic_capture",
                        existed_before=False,
                        deletion_attempted=False,
                        status="not_present",
                        residue_count=0,
                    ),
                )
            )
            with patch.object(
                socket,
                "create_connection",
                side_effect=AssertionError("network forbidden"),
            ) as network:
                result = run_wu2r_resume_acquisition(
                    run_id=RUN_ID,
                    attempt_group_id=ATTEMPT_GROUP_ID,
                    purpose="wu2r-resume-synthetic",
                    query_bytes=QUERY_BYTES,
                    request_bytes=REQUEST_BYTES,
                    expected_query_sha256=QUERY_SHA256,
                    expected_request_sha256=REQUEST_SHA256,
                    failure_evidence_path=primary,
                    emergency_evidence_path=emergency,
                    capture=capture,
                    cleanup=cleanup,
                    clock=lambda: NOW,
                    seeds=seeds,
                    context=context(),
                )
            persisted = (
                json.loads(primary.read_text(encoding="utf-8"))
                if primary.is_file()
                else None
            )
            return result, persisted, capture.call_count, network.call_count

    def replay(
        self,
        response: bytes,
    ):
        with patch.object(
            socket,
            "create_connection",
            side_effect=AssertionError("network forbidden"),
        ) as network:
            result = replay_wu2r_resume_anchor(
                run_id=RUN_ID,
                query_bytes=QUERY_BYTES,
                request_bytes=REQUEST_BYTES,
                expected_query_sha256=QUERY_SHA256,
                expected_request_sha256=REQUEST_SHA256,
                response_bytes=response,
                expected_response_sha256=hashlib.sha256(response).hexdigest(),
                snapshot_metadata=metadata(),
                seeds=SEEDS,
                context=context(),
            )
        return result, network.call_count

    def test_ri01_explicit_linkage_is_preserved(self) -> None:
        response = raw_response()
        result, persisted, capture_calls, network_calls = self.acquire(
            successful_capture(response)
        )

        self.assertEqual(result.run_id, RUN_ID)
        self.assertEqual(result.attempt_group_id, ATTEMPT_GROUP_ID)
        self.assertEqual(result.query_sha256, QUERY_SHA256)
        self.assertEqual(result.request_sha256, REQUEST_SHA256)
        self.assertEqual(
            result.failure_evidence_path.name,
            "failure-evidence.json",
        )
        self.assertEqual(persisted, result.evidence.document)
        self.assertEqual(capture_calls, 1)
        self.assertEqual(network_calls, 0)

    def test_ri02_terminal_capture_failure_has_evidence_only(self) -> None:
        result, persisted, capture_calls, network_calls = self.acquire(
            failed_capture()
        )

        self.assertTrue(result.evidence.durable_evidence)
        self.assertEqual(result.evidence.document["status"], "failed")
        self.assertEqual(
            result.evidence.document["terminal_failure_code"],
            ACQUISITION_TRANSPORT_FAILURE,
        )
        self.assertIsNone(result.candidate_result)
        self.assertIsNone(result.eligible_response_bytes)
        self.assertEqual(persisted, result.evidence.document)
        self.assertEqual(capture_calls, 1)
        self.assertEqual(network_calls, 0)

    def test_ri03_success_retains_identities_and_three_states(self) -> None:
        response = raw_response()
        result, persisted, capture_calls, network_calls = self.acquire(
            successful_capture(response)
        )

        self.assertEqual(result.evidence.document["status"], "succeeded")
        self.assertIsNotNone(result.candidate_result)
        self.assertEqual(result.eligible_response_bytes, response)
        candidates = result.candidate_result.candidate_artifact["payload"][
            "candidates"
        ]
        self.assertEqual(
            [item["candidate_id"] for item in candidates],
            [
                HUANGLING_ATTRACTION,
                HUANGLING_HAMLET,
                LIKENG,
                JIANGLING,
            ],
        )
        self.assertEqual(
            [
                (item.seed, item.status, item.candidate_refs)
                for item in result.candidate_result.seed_matches
            ],
            [
                (
                    "篁岭",
                    "ambiguous",
                    (HUANGLING_HAMLET, HUANGLING_ATTRACTION),
                ),
                ("江岭", "matched", (JIANGLING,)),
                ("李坑", "matched", (LIKENG,)),
                ("庆源", "unmatched", ()),
            ],
        )
        self.assertEqual(persisted, result.evidence.document)
        self.assertEqual(capture_calls, 1)
        self.assertEqual(network_calls, 0)

    def test_ri04_coverage_rejection_has_no_eligible_raw(self) -> None:
        response = raw_response(candidate_elements()[:2])
        result, persisted, capture_calls, network_calls = self.acquire(
            successful_capture(response),
            seeds=("篁岭", "庆源"),
        )

        self.assertEqual(result.evidence.document["status"], "failed")
        self.assertEqual(
            result.evidence.document["terminal_failure_code"],
            ACQUISITION_RESPONSE_FAILURE,
        )
        self.assertEqual(
            result.evidence.document["response_phase"]["status"],
            "rejected",
        )
        self.assertIsNone(result.candidate_result)
        self.assertIsNone(result.eligible_response_bytes)
        self.assertTrue(result.problems)
        self.assertEqual(persisted, result.evidence.document)
        self.assertEqual(capture_calls, 1)
        self.assertEqual(network_calls, 0)

    def test_ri05_response_order_is_output_independent(self) -> None:
        first, first_network = self.replay(raw_response())
        second, second_network = self.replay(
            raw_response(list(reversed(candidate_elements())))
        )

        self.assertEqual(
            first.candidate_result.candidate_artifact,
            second.candidate_result.candidate_artifact,
        )
        self.assertEqual(
            first.candidate_result.seed_matches,
            second.candidate_result.seed_matches,
        )
        self.assertEqual(
            first.candidate_result.record_local_facts,
            second.candidate_result.record_local_facts,
        )
        self.assertEqual(first_network, 0)
        self.assertEqual(second_network, 0)

    def test_ri06_committed_byte_replay_is_offline(self) -> None:
        response = raw_response()
        result, network_calls = self.replay(response)

        self.assertEqual(result.run_id, RUN_ID)
        self.assertEqual(result.response_sha256, hashlib.sha256(response).hexdigest())
        self.assertEqual(result.response_bytes, len(response))
        self.assertEqual(result.network_attempts, 0)
        self.assertFalse(result.problems)
        self.assertEqual(network_calls, 0)


if __name__ == "__main__":
    unittest.main()
