"""WU2R Resume integration contract cases.

Source: synthetic deterministic OSM-shaped inputs authored from the approved
WU2R Resume Plan v0.1. Expected hashes, provider IDs, candidate IDs, seed
states, and failure classifications are handwritten from the frozen
specification; they are not generated by the interfaces under test.

Coverage: explicit acquisition/FER linkage, failure composition,
multi-identity candidate retention, coverage rejection, order independence,
and offline replay.

Non-coverage: live OSM correctness or completeness, HTTP/retry behavior,
real-place identity, route acquisition, evidence rating, recommendation,
feasibility, planning, or UI.
"""

