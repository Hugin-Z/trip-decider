class AdapterContractCase(unittest.TestCase):
    maxDiff = None

    def assert_problem(
        self,
        result: object,
        code: str,
        pointer: str,
        rule: str,
    ) -> None:
        problems = getattr(result, "problems")
        self.assertEqual(len(problems), 1)
        self.assertEqual(problems[0].error_code, code)
        self.assertEqual(problems[0].json_pointer, pointer)
        self.assertEqual(problems[0].schema_rule, rule)

    def test_p01_exact_happy_path_candidate_fields(self) -> None:
        result = normalize_open_data_pois(poi_snapshot(), context())
        self.assertEqual(result.problems, ())
        artifact = result.value
        self.assertIsNotNone(artifact)
        candidate = artifact["payload"]["candidates"][0]
        self.assertEqual(
            candidate["candidate_id"],
            "candidate_8f330e07-0839-4696-8769-19ef50625ec0",
        )
        self.assertEqual(candidate["label"], "Synthetic POI")
        self.assertEqual(candidate["candidate_kind"], "poi")
        self.assertEqual(candidate["provider"]["name"], "osm")
        self.assertEqual(candidate["provider"]["record_id"], "101")
        self.assertEqual(candidate["provider"]["record_type"], "node")
        self.assertEqual(
            candidate["provider"]["categories"],
            [{"code": "tourism=attraction", "label": "attraction"}],
        )
        self.assertEqual(candidate["location"]["crs"], "WGS84")
        self.assertEqual(candidate["location"]["latitude"], 29.1)
        self.assertEqual(candidate["location"]["longitude"], 117.2)
        self.assertEqual(
            candidate["location"]["source_refs"],
            [{"kind": "provider_item", "value": "osm:node:101"}],
        )
        self.assertEqual(artifact["payload"]["generation_stage"], "poi_discovery")

    def test_p02_response_order_independent_candidate_ordering(self) -> None:
        first = poi_element(element_type="way", element_id=202, name="Second")
        second = poi_element(element_type="node", element_id=101, name="First")
        forward = normalize_open_data_pois(poi_snapshot(first, second), context())
        reverse = normalize_open_data_pois(poi_snapshot(second, first), context())
        self.assertEqual(forward.problems, ())
        self.assertEqual(reverse.problems, ())
        self.assertEqual(forward.value, reverse.value)
        self.assertEqual(
            [
                item["candidate_id"]
                for item in forward.value["payload"]["candidates"]
            ],
            [
                "candidate_8f330e07-0839-4696-8769-19ef50625ec0",
                "candidate_b6b4862e-c519-4454-80e2-597c73b739f3",
            ],
        )

