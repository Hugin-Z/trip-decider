"""WU2 adapter contract cases.

Source: synthetic deterministic mappings written from the approved WU2 Plan.
Coverage: strict OSM POI and OSRM route normalization boundaries.
Non-coverage: live connectivity, real Jiangxi facts, provider completeness,
route quality, evidence scoring, feasibility, recommendation, or planning.

Expected values are handwritten from the frozen mapping rules. They are not
generated by the adapters under test.
"""

