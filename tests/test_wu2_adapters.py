CHECKED_AT = "2026-07-28T00:00:00+08:00"
RETRIEVED_AT = "2026-07-28T08:00:00+08:00"
REQUEST_ID = "urn:uuid:00000001-0000-4000-8000-000000000001"
FROM_CANDIDATE = "candidate_00000001-0000-4000-8000-000000000001"
TO_CANDIDATE = "candidate_00000002-0000-4000-8000-000000000002"


def open_policy() -> dict[str, object]:
    return {
        "source_class": "open_data",
        "capture_mode": "persistent_anchor",
        "storage_policy": "persistent_allowed",
        "replay_allowed": True,
        "fixture_allowed": True,
        "policy_checked_at": CHECKED_AT,
        "terms_url": "https://www.openstreetmap.org/copyright",
        "authorization_ref": None,
        "license": {
            "identifier": "ODbL-1.0",
            "url": "https://opendatacommons.org/licenses/odbl/1-0/",
            "attribution": "© OpenStreetMap contributors",
        },
    }


def context() -> IngestionContext:
    return IngestionContext(
        request_ref={
            "artifact_id": REQUEST_ID,
            "artifact_type": "request",
            "payload_sha256": "a" * 64,
            "schema_version": "0.1.0",
        },
        run_id="run_00000001-0000-4000-8000-000000000001",
        created_at=RETRIEVED_AT,
    )


def poi_element(
    *,
    element_type: str = "node",
    element_id: int = 101,
    name: str = "Synthetic POI",
) -> dict[str, object]:
    element: dict[str, object] = {
        "type": element_type,
        "id": element_id,
        "tags": {
            "name": name,
            "tourism": "attraction",
        },
    }
    if element_type == "node":
        element["lat"] = 29.1
        element["lon"] = 117.2
    else:
        element["center"] = {"lat": 29.3, "lon": 117.4}
    return element


def poi_snapshot(*elements: dict[str, object]) -> dict[str, object]:
    selected = list(elements) if elements else [poi_element()]
    return {
        "format_version": "0.1.0",
        "provider": "osm",
        "operation": "overpass-poi-snapshot",
        "crs": "WGS84",
        "retrieved_at": RETRIEVED_AT,
        "request_fingerprint": "b" * 64,
        "response_locator": {
            "kind": "response_location",
            "value": "synthetic-poi.json",
        },
        "data_policy": open_policy(),
        "result": {
            "status": "success",
            "document": {
                "version": 0.6,
                "generator": "Overpass API",
                "osm3s": {"timestamp_osm_base": "2026-07-28T00:00:00Z"},
                "elements": selected,
            },
        },
    }


