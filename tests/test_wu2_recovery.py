"""WU2 Recovery deterministic contract cases.

Source: synthetic deterministic OSM-shaped mappings written from WU2R Plan
v0.1.  Expected candidate IDs and fields are handwritten from the frozen
provider-identity and stable-ID specifications; they are not generated by
the Recovery functions under test.

Coverage: plural provider identities, exact seed accounting, candidate-local
source facts, and pre-route identity guarding.

Non-coverage: live OSM/Overpass data, real-place identity, OSM completeness,
route acquisition, evidence rating, recommendation, feasibility, or planning.
"""

from __future__ import annotations

import copy
import socket
import unittest
from unittest.mock import patch

from trip_decider.adapters import IngestionContext, normalize_open_data_pois
from trip_decider.recovery import (
    RecoveryCandidateResult,
    SeedMatch,
    ingest_candidate_pool,
    prepare_route_endpoints,
)


CHECKED_AT = "2026-07-28T00:00:00+08:00"
RETRIEVED_AT = "2026-07-28T08:00:00+08:00"
REQUEST_ID = "urn:uuid:00000001-0000-4000-8000-000000000001"

HUANGLING_ATTRACTION = "candidate_8f330e07-0839-4696-8769-19ef50625ec0"
HUANGLING_HAMLET = "candidate_2bd4a053-014f-4e14-8e54-79501b37a671"
JIANGLING = "candidate_7dff94ab-4ca4-40ce-b9c7-33750c519679"
LIKENG = "candidate_b6b13e35-55b6-4099-a30b-7027c684a1c5"


def open_policy() -> dict[str, object]:
    return {
        "source_class": "open_data",
        "capture_mode": "persistent_anchor",
        "storage_policy": "persistent_allowed",
        "replay_allowed": True,
        "fixture_allowed": True,
        "policy_checked_at": CHECKED_AT,
        "terms_url": "https://www.openstreetmap.org/copyright",
        "authorization_ref": None,
        "license": {
            "identifier": "ODbL-1.0",
            "url": "https://opendatacommons.org/licenses/odbl/1-0/",
            "attribution": "© OpenStreetMap contributors",
        },
    }


def context() -> IngestionContext:
    return IngestionContext(
        request_ref={
            "artifact_id": REQUEST_ID,
            "artifact_type": "request",
            "payload_sha256": "a" * 64,
            "schema_version": "0.1.0",
        },
        run_id="run_00000001-0000-4000-8000-000000000001",
        created_at=RETRIEVED_AT,
    )


def element(
    *,
    element_type: str,
    element_id: int,
    name: str,
    category_key: str,
    category_value: str,
) -> dict[str, object]:
    item: dict[str, object] = {
        "type": element_type,
        "id": element_id,
        "tags": {
            "name": name,
            category_key: category_value,
        },
    }
    if element_type == "node":
        item["lat"] = 29.10 + element_id / 100000
        item["lon"] = 117.20 + element_id / 100000
    else:
        item["center"] = {
            "lat": 29.30 + element_id / 100000,
            "lon": 117.40 + element_id / 100000,
        }
    return item


