"""WU2R-FER deterministic failure-evidence contract cases.

Source: ten synthetic injected outcomes authored from the approved WU2R-FER
Plan v0.1.  Expected hashes, codes, retry relations, sink states, and cleanup
fields are handwritten from that specification; they are not generated by
the function under test.

Coverage: ledger-first ordering, closed failure classification, retry
relations, primary/emergency persistence, cleanup evidence, redaction, and
atomic-file cleanup.

Non-coverage: network behavior, provider correctness, real OSM identity,
adapters, candidates, anchors, fixtures, planning, or WU2R replay.
"""

from __future__ import annotations

import io
import json
import socket
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path
from unittest.mock import Mock, patch

from trip_decider.acquisition_evidence import (
    ACQUISITION_CLEANUP_FAILURE,
    ACQUISITION_HTTP_FAILURE,
    ACQUISITION_INTERNAL_FAILURE,
    ACQUISITION_LEDGER_FAILURE,
    ACQUISITION_RESPONSE_FAILURE,
    ACQUISITION_TRANSPORT_FAILURE,
    AttemptObservation,
    CleanupItemObservation,
    ResponsePhaseObservation,
    RetryObservation,
    RunnerObservation,
    run_failure_evidenced_acquisition,
)


REQUEST_BYTES = b"data=approved-query"
REQUEST_SHA256 = (
    "0e0298469c9316cbfab084e4813f479631c96d3ca6cecde9fa0bc06cc5e2f7ee"
)
INVALID_JSON_SHA256 = (
    "f1dec6e9ee608550bd1c39ff2b90134059bac5d02e4e78f6410aed2fbd870bd0"
)
NOW = "2026-07-28T12:00:00+08:00"


def attempt(
    *,
    attempt_id: str = "attempt-0001",
    status: str,
    http_status: int | None = None,
    response_bytes: int | None = None,
    response_sha256: str | None = None,
    content_type: str | None = None,
    retry_decision: str,
) -> AttemptObservation:
    return AttemptObservation(
        attempt_id=attempt_id,
        request_sha256=REQUEST_SHA256,
        started_at=NOW,
        completed_at=NOW,
        status=status,
        http_status=http_status,
        response_bytes=response_bytes,
        response_sha256=response_sha256,
        content_type=content_type,
        retry_decision=retry_decision,
    )


def runner_result(
    *attempts: AttemptObservation,
    retries: tuple[RetryObservation, ...] = (),
    response_status: str = "not_evaluated",
    failure_kind: str | None = None,
) -> RunnerObservation:
    return RunnerObservation(
        attempts=attempts,
        retries=retries,
        response_phase=ResponsePhaseObservation(
            status=response_status,
            failure_kind=failure_kind,
        ),
    )


class FailureEvidenceCase(unittest.TestCase):
    maxDiff = None

    def execute(
        self,
        *,
        runner: Mock,
        cleanup: Mock | None = None,
        primary_persist=None,
        emergency_persist=None,
    ):
        cleanup_effect = cleanup or Mock(return_value=())
        standard_output = io.StringIO()
        error_output = io.StringIO()
        with tempfile.TemporaryDirectory(prefix="trip-decider-fer-test-") as raw:
            root = Path(raw)
            primary = root / "runtime" / "failure-evidence.json"
            emergency = root / "emergency" / "failure-evidence.json"
            primary.parent.mkdir()
            emergency.parent.mkdir()
            with (
                patch.object(
                    socket,
                    "create_connection",
                    side_effect=AssertionError("network forbidden"),
                ) as network,
                redirect_stdout(standard_output),
                redirect_stderr(error_output),
            ):
                result = run_failure_evidenced_acquisition(
                    run_id="run_00000001-0000-4000-8000-000000000001",
                    purpose="wu2r-fer-test",
                    request_bytes=REQUEST_BYTES,
                    primary_path=primary,
                    emergency_path=emergency,
                    runner=runner,
                    cleanup=cleanup_effect,
                    clock=lambda: NOW,
                    primary_persist=primary_persist,
                    emergency_persist=emergency_persist,
                )
            primary_document = (
                json.loads(primary.read_text(encoding="utf-8"))
                if primary.is_file()
                else None
            )
            emergency_document = (
                json.loads(emergency.read_text(encoding="utf-8"))
                if emergency.is_file()
                else None
            )
            atomic_residue = sorted(root.rglob("*.tmp"))
            return (
                result,
                primary_document,
                emergency_document,
                runner.call_count,
                cleanup_effect.call_count,
                network.call_count,
                atomic_residue,
                standard_output.getvalue(),
                error_output.getvalue(),
            )

    def test_fe01_transport_timeout_retry_relation_is_preserved(self) -> None:
        retry = RetryObservation(
            original_attempt_id="attempt-0001",
            retry_attempt_id="attempt-0002",
            same_request_sha256=True,
            retry_reason="transport_failure",
        )
        runner = Mock(
            return_value=runner_result(
                attempt(
                    status="transport_failure",
                    retry_decision="retry_scheduled",
                ),
                attempt(
                    attempt_id="attempt-0002",
                    status="succeeded",
                    http_status=200,
                    response_bytes=2,
                    response_sha256=(
                        "44136fa355b3678a1146ad16f7e8649e94fb4fc21fe77e8310c"
                        "060f61caaff8a"
                    ),
                    content_type="application/json",
                    retry_decision="not_applicable",
                ),
                retries=(retry,),
                response_status="accepted",
            )
        )
        result, primary, _, runner_calls, _, network_calls, *_ = self.execute(
            runner=runner
        )

        self.assertEqual(result.document["status"], "succeeded")
        self.assertIsNone(result.document["terminal_failure_code"])
        self.assertEqual(
            result.document["failure_codes"],
            [ACQUISITION_TRANSPORT_FAILURE],
        )
        self.assertEqual(len(result.document["attempts"]), 2)
        self.assertEqual(
            [item["request_sha256"] for item in result.document["attempts"]],
            [REQUEST_SHA256, REQUEST_SHA256],
        )
        self.assertEqual(
            result.document["retries"],
            [
                {
                    "original_attempt_id": "attempt-0001",
                    "retry_attempt_id": "attempt-0002",
                    "same_request_sha256": True,
                    "retry_reason": "transport_failure",
                }
            ],
        )
        self.assertEqual(primary, result.document)
        self.assertEqual(runner_calls, 1)
        self.assertEqual(network_calls, 0)

