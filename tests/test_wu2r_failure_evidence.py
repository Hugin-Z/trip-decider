        self.assertEqual(result.document["status"], "evidence_persistence_failed")
        self.assertEqual(
            result.document["terminal_failure_code"],
            ACQUISITION_LEDGER_FAILURE,
        )
        self.assertEqual(result.document["failure_codes"], [ACQUISITION_LEDGER_FAILURE])
        self.assertEqual(result.document["attempts"], [])
        self.assertEqual(result.document["persistence"]["primary_status"], "failed")
        self.assertTrue(result.document["persistence"]["emergency_attempted"])
        self.assertEqual(
            result.document["persistence"]["emergency_status"],
            "succeeded",
        )
        self.assertIsNone(primary)
        self.assertEqual(emergency, result.document)
        self.assertTrue(result.durable_evidence)
        self.assertEqual(runner_calls, 0)
        self.assertEqual(cleanup_calls, 0)
        self.assertEqual(network_calls, 0)

