    def test_fe09_terminal_primary_failure_retains_complete_emergency(self) -> None:
        primary_calls = 0

        def fail_after_started(path: Path, payload: bytes) -> None:
            nonlocal primary_calls
            primary_calls += 1
            if primary_calls > 1:
                raise OSError("private terminal write failure")
            path.write_bytes(payload)

        runner = Mock(
            return_value=runner_result(
                attempt(
                    status="http_response_failure",
                    http_status=503,
                    response_bytes=3,
                    response_sha256=(
                        "2f05d4b689d270cafb02285f35f44866bfe1dc3fc3a887d70e"
                        "ca9320887028d"
                    ),
                    content_type="text/plain",
                    retry_decision="not_retryable_http",
                )
            )
        )
        (
            result,
            primary,
            emergency,
            runner_calls,
            _,
            network_calls,
            *_,
        ) = self.execute(runner=runner, primary_persist=fail_after_started)

        self.assertEqual(primary_calls, 2)
        self.assertEqual(
            result.document["terminal_failure_code"],
            ACQUISITION_LEDGER_FAILURE,
        )
        self.assertEqual(
            result.document["failure_codes"],
            [ACQUISITION_HTTP_FAILURE, ACQUISITION_LEDGER_FAILURE],
        )
        self.assertEqual(result.document["attempts"][0]["http_status"], 503)
        self.assertEqual(result.document["persistence"]["primary_status"], "failed")
        self.assertEqual(
            result.document["persistence"]["emergency_status"],
            "succeeded",
        )
        self.assertEqual(primary["status"], "started")
        self.assertEqual(emergency, result.document)
        self.assertEqual(result.emergency_path.name, "failure-evidence.json")
        self.assertTrue(result.durable_evidence)
        self.assertEqual(runner_calls, 1)
        self.assertEqual(network_calls, 0)

