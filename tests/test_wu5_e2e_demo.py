    def test_e2e06_invocation_is_deterministic_atomic_and_offline(
        self,
    ) -> None:
        first_planning = self._planning_root("e2e06-first-planning")
        second_planning = self._planning_root("e2e06-second-planning")
        first_root = self.temp_root / "e2e06-first-output"
        second_root = self.temp_root / "e2e06-second-output"
        trace: list[str] = []

        def traced_recovery(*args, **kwargs):
            trace.append("recovery")
            return real_recovery(*args, **kwargs)

        def traced_evidence(*args, **kwargs):
            trace.append("evidence")
            return real_evidence(*args, **kwargs)

        def traced_planner(*args, **kwargs):
            trace.append("planning")
            return real_planner(*args, **kwargs)

        real_render = getattr(e2e_module, "_render_html", lambda *args: b"")
        real_install = getattr(
            e2e_module,
            "_install_directory",
            lambda *args: None,
        )

        def traced_render(*args, **kwargs):
            trace.append("render")
            return real_render(*args, **kwargs)

        def traced_install(*args, **kwargs):
            trace.append("install")
            return real_install(*args, **kwargs)

        with (
            patch(
                "trip_decider.e2e_demo.run_wu2_recovery",
                side_effect=traced_recovery,
                create=True,
            ) as recovery_mock,
            patch(
                "trip_decider.e2e_demo.run_evidence_runtime",
                side_effect=traced_evidence,
                create=True,
            ) as evidence_mock,
            patch(
                "trip_decider.e2e_demo.run_coarse_planner",
                side_effect=traced_planner,
                create=True,
            ) as planner_mock,
            patch(
                "trip_decider.e2e_demo._render_html",
                side_effect=traced_render,
                create=True,
            ) as render_mock,
            patch(
                "trip_decider.e2e_demo._install_directory",
                side_effect=traced_install,
                create=True,
            ) as install_mock,
            patch.object(
                socket.socket,
                "connect",
                side_effect=AssertionError("network forbidden"),
            ) as socket_mock,
            patch.object(
                urllib.request,
                "urlopen",
                side_effect=AssertionError("network forbidden"),
            ) as urlopen_mock,
        ):
            first = run_e2e_demo(ANCHOR, first_planning, first_root)
            second = run_e2e_demo(ANCHOR, second_planning, second_root)
        self.assertEqual(first.problems, ())
        self.assertEqual(second.problems, ())
        self.assertIsNotNone(first.value)
        self.assertIsNotNone(second.value)
        self.assertEqual(recovery_mock.call_count, 2)
        self.assertEqual(evidence_mock.call_count, 2)
        self.assertEqual(planner_mock.call_count, 2)
        self.assertEqual(render_mock.call_count, 2)
        self.assertEqual(install_mock.call_count, 2)
        self.assertEqual(
            trace,
            [
                "recovery",
                "evidence",
                "planning",
                "render",
                "install",
                "recovery",
                "evidence",
                "planning",
                "render",
                "install",
            ],
        )
        self.assertEqual(_file_bytes(first_root), _file_bytes(second_root))
        self.assertEqual(socket_mock.call_count, 0)
        self.assertEqual(urlopen_mock.call_count, 0)
        self.assertEqual(first.value.network_attempts, 0)
        self.assertEqual(first.value.llm_calls, 0)
        self.assertEqual(_staging_residue(self.temp_root, first_root.name), ())
        self.assertEqual(
            _staging_residue(self.temp_root, second_root.name),
            (),
        )

        nonempty = self.temp_root / "e2e06-nonempty"
        nonempty.mkdir()
        marker = nonempty / "marker.txt"
        marker.write_text("preserve", encoding="utf-8")
        with (
            patch(
                "trip_decider.e2e_demo.run_wu2_recovery",
                wraps=real_recovery,
                create=True,
            ) as recovery_mock,
            patch(
                "trip_decider.e2e_demo.run_evidence_runtime",
                wraps=real_evidence,
                create=True,
            ) as evidence_mock,
            patch(
                "trip_decider.e2e_demo.run_coarse_planner",
                wraps=real_planner,
                create=True,
            ) as planner_mock,
        ):
            rejected = run_e2e_demo(ANCHOR, first_planning, nonempty)
        self.assertIsNone(rejected.value)
        self.assertEqual(
            rejected.problems[0].error_code,
            "E2E_OUTPUT_ROOT_INVALID",
        )
        self.assertEqual(recovery_mock.call_count, 0)
        self.assertEqual(evidence_mock.call_count, 0)
        self.assertEqual(planner_mock.call_count, 0)
        self.assertEqual(marker.read_text(encoding="utf-8"), "preserve")

        failed_root = self.temp_root / "e2e06-failed-output"
        forced_problem = ValidationProblem(
            error_code="EVIDENCE_RUNTIME_INPUT_INVALID",
            artifact_path="input/forced",
            json_pointer="/forced",
            schema_rule="injected",
            expected="accepted evidence input",
            actual_type="injected",
            message="Evidence Runtime input is invalid.",
        )
        with (
            patch(
                "trip_decider.e2e_demo.run_wu2_recovery",
                wraps=real_recovery,
                create=True,
            ) as recovery_mock,
            patch(
                "trip_decider.e2e_demo.run_evidence_runtime",
                return_value=ValidationResult(None, (forced_problem,)),
                create=True,
            ) as evidence_mock,
            patch(
                "trip_decider.e2e_demo.run_coarse_planner",
                wraps=real_planner,
                create=True,
            ) as planner_mock,
            patch(
                "trip_decider.e2e_demo._render_html",
                wraps=real_render,
                create=True,
            ) as render_mock,
        ):
            failed = run_e2e_demo(
                ANCHOR,
                first_planning,
                failed_root,
            )
        self.assertIsNone(failed.value)
        self.assertEqual(failed.problems, (forced_problem,))
        self.assertEqual(recovery_mock.call_count, 1)
        self.assertEqual(evidence_mock.call_count, 1)
        self.assertEqual(planner_mock.call_count, 0)
        self.assertEqual(render_mock.call_count, 0)
        self.assertFalse(failed_root.exists())
        self.assertEqual(
            _staging_residue(self.temp_root, failed_root.name),
            (),
        )


