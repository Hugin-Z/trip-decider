def _json(path: Path) -> dict[str, object]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise AssertionError("expected JSON object")
    return value


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def _files(root: Path) -> tuple[str, ...]:
    return tuple(
        sorted(
            path.relative_to(root).as_posix()
            for path in root.rglob("*")
            if path.is_file()
        )
    )


def _file_bytes(root: Path) -> dict[str, bytes]:
    return {
        relative: root.joinpath(*relative.split("/")).read_bytes()
        for relative in _files(root)
    }


def _staging_residue(parent: Path, output_name: str) -> tuple[Path, ...]:
    return tuple(
        path
        for path in parent.iterdir()
        if path.name.startswith(f".{output_name}.")
        and path.name.endswith(".staging")
    )


class _StructureParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.section_ids: list[str] = []
        self.links: list[str] = []
        self.tags: list[str] = []

    def handle_starttag(
        self,
        tag: str,
        attrs: list[tuple[str, str | None]],
    ) -> None:
        self.tags.append(tag)
        values = dict(attrs)
        if tag == "section" and isinstance(values.get("id"), str):
            self.section_ids.append(values["id"])
        if tag == "a" and isinstance(values.get("href"), str):
            self.links.append(values["href"])


class EndToEndDemoCase(unittest.TestCase):
    """Six independent behaviors across the real offline pipeline."""

    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory(
            prefix="trip-decider-wu5-e2e-"
        )
        self.temp_root = Path(self.temporary.name)

    def tearDown(self) -> None:
        self.temporary.cleanup()

    def _planning_root(
        self,
        name: str,
        *,
        day_count: int = 2,
    ) -> Path:
        root = self.temp_root / name
        _write_planning_root(root, day_count)
        return root

    def _run(
        self,
        name: str,
        *,
        day_count: int = 2,
        output_root: Path | None = None,
    ):
        planning_root = self._planning_root(
            f"{name}-planning",
            day_count=day_count,
        )
        destination = output_root or self.temp_root / f"{name}-output"
        with (
            patch.object(
                socket.socket,
                "connect",
                side_effect=AssertionError("network forbidden"),
            ) as socket_mock,
            patch.object(
                urllib.request,
                "urlopen",
                side_effect=AssertionError("network forbidden"),
            ) as urlopen_mock,
        ):
            result = run_e2e_demo(ANCHOR, planning_root, destination)
        self.assertEqual(socket_mock.call_count, 0)
        self.assertEqual(urlopen_mock.call_count, 0)
        return planning_root, destination, result

    def test_e2e01_real_anchor_emits_complete_layout(self) -> None:
        _, output_root, result = self._run("e2e01")
        self.assertEqual(result.problems, ())
        self.assertIsNotNone(result.value)
        self.assertEqual(_files(output_root), EXPECTED_FILES)

        summary = _json(output_root / "run-summary.json")
        planning_summary = _json(
            output_root / "planning" / "run-summary.json"
        )
        self.assertEqual(
            set(summary),
            {
                "schema_version",
                "run_id",
                "completion_status",
                "input",
                "stages",
                "result",
                "report",
                "network_attempts",
                "llm_calls",
            },
        )
        self.assertEqual(summary["schema_version"], "wu5-e2e-demo-run/1.0")
        self.assertEqual(summary["run_id"], planning_summary["run_id"])
        self.assertEqual(summary["completion_status"], "completed")
        self.assertEqual(
            summary["result"],
            {
                "planning_status": "conditionally_feasible",
                "draft_created": True,
                "publishable": False,
                "generation_allowed_input": False,
                "scheduled_count": 2,
                "blocked_count": 2,
            },
        )
        self.assertEqual(summary["network_attempts"], 0)
        self.assertEqual(summary["llm_calls"], 0)
        self.assertNotIn("run_summary_sha256", summary)
        for stage_name in ("recovery", "evidence", "planning"):
            stage = summary["stages"][stage_name]
            stage_path = output_root.joinpath(
                *stage["summary_path"].split("/")
            )
            self.assertEqual(stage["summary_sha256"], _sha256(stage_path))
        self.assertEqual(
            summary["report"]["sha256"],
            _sha256(output_root / "report" / "index.html"),
        )
        self.assertNotIn(
            str(self.temp_root),
            json.dumps(summary, ensure_ascii=False, sort_keys=True),
        )

    def test_e2e02_html_shows_only_unscheduled_coarse_days(self) -> None:
        _, output_root, result = self._run("e2e02")
        self.assertEqual(result.problems, ())
        self.assertIsNotNone(result.value)
        raw = (output_root / "report" / "index.html").read_bytes()
        self.assertFalse(raw.startswith(b"\xef\xbb\xbf"))
        html_text = raw.decode("utf-8", errors="strict")
        parser = _StructureParser()
        parser.feed(html_text)

        self.assertEqual(
            parser.section_ids,
            [
                "status",
                "itinerary",
                "blockers",
                "evidence",
                "conditions",
                "audit",
            ],
        )
        self.assertEqual(tuple(parser.links), EXPECTED_LINKS)
        self.assertNotIn("script", parser.tags)
        self.assertNotIn("img", parser.tags)
        self.assertNotIn("link", parser.tags)
        self.assertIn("第1天", html_text)
        self.assertIn("江岭", html_text)
        self.assertIn("第2天", html_text)
        self.assertIn("李坑", html_text)
        self.assertEqual(html_text.count("具体时刻：尚未安排"), 2)
        self.assertNotIn("start_at", html_text)
        self.assertNotIn("end_at", html_text)
        for forbidden in (
            "推荐顺序",
            "最佳路线",
            "建议上午",
            "预计游览时长",
            "距离",
            "交通耗时",
            "热度",
            "优化分数",
        ):
            self.assertNotIn(forbidden, html_text)

