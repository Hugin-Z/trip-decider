    def test_ve_17_failed_transport_leaves_no_temp_python(self) -> None:
        temp_root = Path(tempfile.gettempdir())
        before = {
            path.resolve()
            for path in temp_root.glob("trip-decider-wu1-*.py")
        }
        script_literal = str(VERIFY_SCRIPT).replace("'", "''")
        python_literal = str(PROJECT_PYTHON).replace("'", "''")
        root_literal = str(PROJECT_ROOT).replace("'", "''")
        harness = (
            "$ErrorActionPreference = 'Stop'\n"
            f". '{script_literal}'\n"
            "$code = \"raise SystemExit(5)\"\n"
            "$result = Invoke-Wu1PythonTransport "
            f"-PythonExe '{python_literal}' "
            "-PythonCode $code "
            f"-RepoRoot '{root_literal}'\n"
            "exit $result\n"
        )
        handle, harness_path_value = tempfile.mkstemp(
            prefix="trip-decider-wu1r-",
            suffix=".ps1",
        )
        os.close(handle)
        harness_path = Path(harness_path_value)
        try:
            harness_path.write_text(harness, encoding="utf-8", newline="\n")
            result = subprocess.run(
                [
                    "powershell",
                    "-NoProfile",
                    "-ExecutionPolicy",
                    "Bypass",
                    "-File",
                    str(harness_path),
                ],
                cwd=PROJECT_ROOT,
                text=True,
                capture_output=True,
                check=False,
            )
        finally:
            harness_path.unlink(missing_ok=True)
        after = {
            path.resolve()
            for path in temp_root.glob("trip-decider-wu1-*.py")
        }
        self.assertEqual(result.returncode, 5)
        self.assertEqual(after, before)
        self.assertFalse(any(PROJECT_ROOT.rglob("trip-decider-wu1-*.py")))

