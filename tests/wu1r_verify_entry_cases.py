def _problem(
    code: str,
    path: str,
    pointer: str,
    rule: str,
    *,
    expected: str = "",
    actual_type: str = "",
    message: str = "Specification-authored deterministic problem.",
) -> ValidationProblem:
    return ValidationProblem(
        error_code=code,
        artifact_path=path,
        json_pointer=pointer,
        schema_rule=rule,
        expected=expected,
        actual_type=actual_type,
        message=message,
    )


class FakeDependencies:
    """Clean deterministic surface with one-attribute dirty mutations."""

